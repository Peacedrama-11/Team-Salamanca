function lookup(value: string, language: Language) {
  const normalized = value.replace(/\s+/g, ' ').trim();
  if (/^Explore .+ with fictional, session-only demo data\.$/.test(normalized)) {
    return language === 'zh'
      ? '使用虚构的演示数据探索此页面。资料仅在本次会话中保留。'
      : language === 'ms'
        ? 'Terokai halaman ini dengan data demo rekaan. Maklumat hanya disimpan untuk sesi ini.'
        : value;
  }
  if (language === 'ms') return ms[normalized] ?? value;
  if (language === 'zh') return zh[normalized] ?? value;
  return value;
}

function lookupAttribute(value: string, language: Language) {
  if (language === 'ms') return attributeTranslations[value] ?? value;
  if (language === 'zh') return zhAttributeTranslations[value] ?? value;
  return value;
}

function translateTextNode(node: Text, language: Language) {
  const current = node.nodeValue ?? '';
  let source = originalText.get(node);
  if (source === undefined || (current !== lookup(source, 'en') && current !== lookup(source, 'ms') && current !== lookup(source, 'zh'))) {
    source = current;
    originalText.set(node, source);
  }
  const match = source.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return;
  const translated = lookup(match[2].replace(/\s+/g, ' ').trim(), language);
  const next = `${match[1]}${translated}${match[3]}`;
  if (current !== next) node.nodeValue = next;
}

function translateElementAttributes(element: Element, language: Language) {
  const names = ['aria-label', 'placeholder', 'title', 'alt'];
  let originals = originalAttributes.get(element);
  if (!originals) {
    originals = new Map();
    originalAttributes.set(element, originals);
  }
  for (const name of names) {
    const current = element.getAttribute(name);
    if (current === null) continue;
    let source = originals.get(name);
    const expectedEnglish = source ?? current;
    const expectedMalay = source === undefined ? current : lookupAttribute(source, 'ms');
    const expectedChinese = source === undefined ? current : lookupAttribute(source, 'zh');
    if (source === undefined || (current !== expectedEnglish && current !== expectedMalay && current !== expectedChinese)) {
      source = current;
      originals.set(name, source);
    }
    const translated = lookupAttribute(source, language);
    if (current !== translated) element.setAttribute(name, translated);
  }
}

function translateTree(root: ParentNode, language: Language) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) translateTextNode(node as Text, language);
  if (root instanceof Element) translateElementAttributes(root, language);
  root.querySelectorAll?.('*').forEach(element => translateElementAttributes(element, language));
}

export function useDocumentLanguage(language: Language) {
  const languageRef = useRef(language);
  languageRef.current = language;

  useEffect(() => {
    document.documentElement.lang = language === 'ms' ? 'ms' : language === 'zh' ? 'zh-CN' : 'en';
    translateTree(document.body, language);
  }, [language]);

  useEffect(() => {
    const observer = new MutationObserver(records => {
      for (const record of records) {
        if (record.type === 'characterData' && record.target instanceof Text) {
          translateTextNode(record.target, languageRef.current);
          continue;
        }
        record.addedNodes.forEach(node => {
          if (node instanceof Text) translateTextNode(node, languageRef.current);
          else if (node instanceof Element) translateTree(node, languageRef.current);
        });
        if (record.type === 'attributes' && record.target instanceof Element) {
          translateElementAttributes(record.target, languageRef.current);
        }
      }
    });
    observer.observe(document.body, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ['aria-label', 'placeholder', 'title', 'alt'],
    });
    return () => observer.disconnect();
  }, []);
}

export function LanguageSelect({
  language,
  onChange,
}: {
  language: Language;
  onChange: (language: Language) => void;
}) {
  return (
    <label className="language-picker">
      <span>{language === 'ms' ? 'Bahasa' : language === 'zh' ? '语言' : 'Language'}</span>
      <select
        aria-label={language === 'ms' ? 'Pilih bahasa' : language === 'zh' ? '选择语言' : 'Choose language'}
        value={language}
        onChange={event => onChange(event.target.value as Language)}
      >
        <option value="en">English</option>
        <option value="ms">Bahasa Melayu</option>
        <option value="zh">简体中文</option>
      </select>
    </label>
  );
}
